@dataclass
class SourceReport:
    """What loading one source did."""

    source: str
    records: int = 0
    retired: int = 0
    error: str | None = None
    #: Rows `catalogue.load_record` refused. The rest of the source still
    #: loaded; see `LOAD_ONE`.
    rejected: int = 0
    #: Why, for the first few. One line each, for the run summary and the job log.
    rejects: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return self.error is None


@dataclass
class LoadReport:
    """What a whole load did, so a caller can print it and CI can assert on it."""

    run_id: UUID | None = None
    sources: list[SourceReport] = field(default_factory=list)
    products: int = 0
    offers: int = 0
    identities: int = 0

    @property
    def loaded(self) -> list[SourceReport]:
        return [report for report in self.sources if report.ok]

    @property
    def failures(self) -> list[SourceReport]:
        return [report for report in self.sources if not report.ok]

    @property
    def ok(self) -> bool:
        return not self.failures

    @property
    def records(self) -> int:
        return sum(report.records for report in self.loaded)


def may_retire(write_status: Any, truncated: Any) -> tuple[bool, str]:
    """Whether one source's collection may be read as the whole of a catalogue.

    The one rule that decides whether products get withdrawn, in one place
    because it has two callers that must never disagree. `plan_load` asks it of
    a manifest entry; the worker asks it of the source it has just collected.

    They *did* disagree. `plan_load` has refused to retire against a truncated
    dump since the day the flag was added, and the worker — which is what runs
    every night — decided `whole` from the artifact's write status alone and
    never looked at `truncated` at all. So the safety property the README
    states, the tests pin and the scrapers are careful to feed had no effect on
    the only path that uses it in production. On 2026-08-10 that retired 24,856
    products across seventeen sources; ceram-decor is still short 543 of 758
    because its dumps keep being truncated and each run withdraws what the last
    one could not read.
    """
    if write_status != "replaced":
        # 'preserved_existing_nonempty' is the dangerous one: the run wrote
        # nothing and an older file was left in place. It looks complete and
        # is not, and retiring against it withdraws a live catalogue.
        return False, f"write_status {write_status!r}, not written by this run"
    if truncated:
        return False, "run hit its cap, so the file is not the whole catalogue"
    return True, ""


def ensure_staging(connection: Connection) -> None:
    """Create this connection's private staging table."""
    with connection.cursor() as cursor:
        cursor.execute(CREATE_STAGING)


def _load_staged(
    connection: Connection, cursor: Any, report: SourceReport, run_id: UUID | None
) -> None:
    """Load every staged row, and let a row the database refuses cost only itself.

    The fast path is unchanged and is what nearly every source takes: one
    statement, one `load_record` call per row, no round trip per record. It runs
    inside a savepoint so that failing does not poison the transaction the
    caller is holding — which still has the retire step to do.

    Only when that statement fails is the source re-loaded a row at a time, each
    under its own savepoint, so the rows that are fine land and the ones that
    are not are counted and named. It is a round trip per record and it is only
    ever paid by a source that has something wrong with it.

    Rejected rows stay in staging deliberately. Retirement asks "what did this
    dump not list", and a row we failed to load was still listed — dropping it
    from the question would retire a product the shop still sells.
    """
    try:
        with connection.transaction():
            cursor.execute(LOAD, {"run": run_id})
        return
    except psycopg.Error as error:
        LOGGER.warning(
            "load.batch_refused",
            source=report.source,
            error=_reason(error),
            detail="reloading one record at a time",
        )

    cursor.execute(STAGED_LINES)
    for line in [row["line_number"] for row in cursor.fetchall()]:
        try:
            with connection.transaction():
                cursor.execute(LOAD_ONE, {"run": run_id, "line": line})
        except psycopg.Error as error:
            report.rejected += 1
            if len(report.rejects) < REJECT_SAMPLE:
                report.rejects.append(f"line {line}: {_reason(error)}")

    if report.rejected:
        LOGGER.warning(
            "load.records_refused",
            source=report.source,
            rejected=report.rejected,
            of=report.records,
            reasons=report.rejects,
        )


def _reason(error: psycopg.Error) -> str:
    """The first line of a database error: the condition, without the context."""
    return str(error).strip().splitlines()[0] if str(error).strip() else error.__class__.__name__


def read_ndjson(path: Path) -> Iterator[dict[str, Any]]:
    """Yield each record in a dump file, skipping blank lines.

    A generator rather than a list: the whole point of `COPY` here is that a
    4,473-record source streams through without both the file and the parsed
    records being resident at once.
    """
    opener = gzip.open if path.name.endswith(".gz") else open
    with opener(path, "rt", encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                yield json.loads(line)


def load_source(
    connection: Connection,
    source: str,
    records: Iterable[dict[str, Any]],
    *,
    whole: bool,
    run_id: UUID | None = None,
    stock_trends_enabled: bool = False,
) -> SourceReport:
    """Stage, load and (if the file is whole) retire, in one transaction.

    Either all four steps happen for this source or none do. That is the point
    of the rewrite: the previous four separate `psql` invocations could be
    interrupted between any two, leaving staging populated, retirement
    half-applied, and the source counted as loaded.

    Retirement is asked of the staged rows rather than of a timestamp.
    `last_seen_at` carries the moment the *page* was fetched, which is always
    older than the load, so a clock comparison retires the entire source.
    """
    report = SourceReport(source=source)

    with connection.transaction(), connection.cursor() as cursor:
        # A transaction-local custom setting lets the database function keep
        # raw records intact while gating only relational stock history. It
        # cannot leak through a pooled connection after this source commits.
        cursor.execute(
            "select set_config('catalogue.stock_trends_enabled', %(enabled)s, true)",
            {"enabled": "true" if stock_trends_enabled else "false"},
        )
        cursor.execute("truncate import_staging")

        # One row per record, the JSON sent as text. Binary would need the jsonb
        # type oid and buys nothing: the cost of this load is the `load_record`
        # call per row, not the parse.
        with cursor.copy("copy import_staging (source_file, record) from stdin") as copy:
            for record in records:
                copy.write_row((source, json.dumps(record, ensure_ascii=False, default=str)))
                report.records += 1

        _load_staged(connection, cursor, report, run_id)

        if whole:
            # Asked while this file is still staged, so "not in the dump" is a
            # question about the dump itself. Only a complete dump is grounds
            # for it, which is why `whole` is a parameter decided by `plan_load`
            # rather than something inferred here from a filename.
            cursor.execute(RETIRE, {"source": source})
            report.retired = max(cursor.rowcount, 0)

        cursor.execute("truncate import_staging")

    metrics.offers_written(report.records)
    LOGGER.info(
        "load.source",
        source=source,
        records=report.records,
        rejected=report.rejected,
        retired=report.retired,
        whole=whole,
    )
    return report


def describe_sources(
    connection: Connection, sources: dict[str, dict[str, Any]], only: set[str] | None = None
) -> int:
    """Copy each source's identity from sources.json into catalogue.sources."""
    written = 0
    with connection.cursor() as cursor:
        for source_id, config in sorted(sources.items()):
            if only is not None and source_id not in only:
                continue
            # Only the keys that describe the shop; the scraper settings beside
            # them are the crawler's business and would be noise in a reporting
            # database.
            metadata = {key: config[key] for key in ("country", "scope") if config.get(key)}
            cursor.execute(
                DESCRIBE,
                {
                    "id": source_id,
                    "label": config.get("label"),
                    "url": config.get("url"),
                    "metadata": json.dumps(metadata, sort_keys=True),
                },
            )
            written += 1
    return written


def load_dump(
    connection: Connection,
    plans: list[Load],
    sources: dict[str, dict[str, Any]],
    described: set[str],
    *,
    keep_stale: bool = False,
    run_id: UUID | None = None,
    stock_trends_enabled: bool = False,
) -> LoadReport:
    """Load every planned source, stepping over the ones that fail.

    One source failing is one supplier's data, not the load's. A record the
    schema rejects — a price with no currency, say — used to abort everything
    after it, so a defect in the third of sixty-three sources cost the other
    sixty. Each source is its own transaction, and a failure is recorded and
    stepped over, with the import run marked failed at the end so that nothing
    looks clean that was not.
    """
    report = LoadReport()
    ensure_staging(connection)

    with connection.cursor() as cursor:
        cursor.execute(
            "insert into catalogue.import_runs (status, importer_version, run_id) "
            "values ('running', %(version)s, %(run)s) returning id",
            {"version": "mb_ceramics_catalogue.storage.postgres", "run": run_id},
        )
        row = cursor.fetchone()
        assert row is not None
        report.run_id = row["id"]

    describe_sources(connection, sources, described)

    for plan in plans:
        try:
            report.sources.append(
                load_source(
                    connection,
                    plan.source,
                    read_ndjson(plan.path),
                    whole=plan.whole and not keep_stale,
                    run_id=report.run_id,
                    stock_trends_enabled=stock_trends_enabled,
                )
            )
        except (psycopg.Error, json.JSONDecodeError) as failure:
            # The server's complaint, not a traceback: it is the line that says
            # which part of the record the dump got wrong. The transaction has
            # already rolled back, so staging is clean for the next source.
            text = str(failure).strip()
            reason = text.splitlines()[0] if text else "unknown error"
            report.sources.append(SourceReport(source=plan.source, error=reason[:500]))
            LOGGER.warning("load.source_failed", source=plan.source, error=reason)

    with connection.cursor() as cursor:
        cursor.execute(
            "update catalogue.import_runs set status = %(status)s, finished_at = now(), "
            "record_count = %(count)s where id = %(id)s",
            {
                "status": "failed" if report.failures else "complete",
                "count": report.records,
                "id": report.run_id,
            },
        )
        cursor.execute(
            "select (select count(*) from catalogue.source_products) as products,"
            " (select count(*) from catalogue.offer_observations) as offers,"
            " (select count(*) from catalogue.source_products"
            "   where record_format like '%%identity%%') as identities"
        )
        totals = cursor.fetchone()
        assert totals is not None
        report.products = int(totals["products"])
        report.offers = int(totals["offers"])
        report.identities = int(totals["identities"])

    return report
