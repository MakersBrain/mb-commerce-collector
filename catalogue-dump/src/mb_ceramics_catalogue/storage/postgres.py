"""Load a catalogue dump into the PostgreSQL `catalogue` schema, in-process.

Streams each source's records into a staging table with `COPY`, then calls
`catalogue.load_record` over it. That avoids quoting six thousand JSON literals
into a script and is an order of magnitude faster than one statement per record.

Four things changed when this stopped shelling out to `psql` (§5.3), and each
was a real problem rather than a style preference:

* **No `psql` on PATH.** The loader could not run inside the worker's image,
  which is why the load was a separate manual step joined to the scrape by files
  on disk.
* **Real parameters.** The run id and the source name used to be spliced in with
  `RETIRE.replace("%(source)s", f"'{source}'")`. Source ids come from a
  checked-in file so it was not an injection surface, but it is now impossible
  for it to become one.
* **One transaction per source**, covering stage, `load_record`, retire-unseen
  and truncate. A crash between the four `psql` invocations used to leave
  staging populated and retirement half-applied, with the source counted as
  loaded.
* **A temporary staging table per connection**, not one shared unlogged table.
  This is required by concurrency, not optional: two workers loading at once
  would otherwise stage into each other's rows and retire against the union —
  which, for two sources, retires everything each of them did not list.

`plan_load` and `authoritative` are unchanged, deliberately and to the letter.
They are the load's safety property — an empty file is never grounds for
retirement, a partial file only ever adds, a truncated run is adds-only — and
`tests/test_load_planning.py` pins every one of them.
"""

from __future__ import annotations

import gzip
import json
from collections.abc import Iterable, Iterator
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from uuid import UUID

import psycopg

from mb_ceramics_catalogue.observability import logging as obs
from mb_ceramics_catalogue.observability import metrics

LOGGER = obs.get_logger("catalogue.load")

Connection = psycopg.Connection[dict[str, Any]]

# A temporary table, so two workers loading at once cannot see each other's
# rows. Created once per connection and truncated per source; `on commit drop`
# would take it away between sources.
CREATE_STAGING = """
create temporary table if not exists import_staging (
  line_number bigint generated by default as identity,
  source_file text,
  record jsonb
) on commit preserve rows
"""

LOAD = """
select catalogue.load_record(record, %(run)s::uuid)
  from import_staging
 order by line_number
"""

# The same call for one staged row, used only after the set-based one has
# failed. `catalogue.load_record` enforces real invariants — a price with no
# currency, a quantity with no unit — and raises on the row that breaks one.
# Raising is right; what was wrong is that it happened inside a single statement
# covering the whole source, so one unpriceable variant discarded every other
# record with it. On 2026-08-11 that cost art-academy-direct all 4,980 of its
# rows, and gwn-pottery and sheffield-pottery a run each in the days before.
LOAD_ONE = """
select catalogue.load_record(record, %(run)s::uuid)
  from import_staging
 where line_number = %(line)s
"""

STAGED_LINES = "select line_number from import_staging order by line_number"

#: Rejected rows quoted in the report. Enough to see the shape of the problem;
#: a source where every row is rejected does not need six thousand copies of it.
REJECT_SAMPLE = 5

RETIRE = """
update catalogue.source_products p
   set active = false
 where p.source_id = %(source)s
   and p.active
   and not exists (
     select 1 from import_staging s
      where s.record->>'external_id' = p.external_id
   )
"""

# `catalogue.load_record` creates a source row from the id alone, because a
# record carries no description of the shop it came from. Everything a reader
# needs to tell one supplier from another — the name to print, the shop it
# points at, the country it ships from — is in sources.json, so it is copied
# across here.
DESCRIBE = """
insert into catalogue.sources (id, label, homepage_url, metadata)
values (%(id)s, %(label)s, %(url)s, %(metadata)s::jsonb)
on conflict (id) do update
   set label = coalesce(excluded.label, catalogue.sources.label),
       homepage_url = coalesce(excluded.homepage_url, catalogue.sources.homepage_url),
       -- Merged rather than replaced: this file is not the only thing that has
       -- an opinion about a source, and it should not drop what it never set.
       metadata = catalogue.sources.metadata || excluded.metadata,
       updated_at = now()
"""


# ---------------------------------------------------------------------------
# Planning: which file, and whether it may be treated as a whole catalogue
# ---------------------------------------------------------------------------


def records_in(path: Path) -> int:
    """How many records a dump file holds, ignoring blank lines."""
    if not path.exists():
        return 0
    opener = gzip.open if path.name.endswith(".gz") else open
    with opener(path, "rt", encoding="utf-8") as handle:
        return sum(1 for line in handle if line.strip())


class Load:
    """One source's contribution to a load: which file, and whether it is whole.

    `whole` is what decides retirement. A complete dump is the entirety of a
    supplier's catalogue, so anything of theirs it does not list has been
    withdrawn. A `.partial.ndjson` is a run that stopped early, which is not a
    smaller catalogue but an unfinished one — retiring against it would withdraw
    products that are still for sale and never appeared in the file only because
    nobody got that far.
    """

    def __init__(self, source: str, path: Path, whole: bool, records: int) -> None:
        self.source = source
        self.path = path
        self.whole = whole
        self.records = records

    def __repr__(self) -> str:  # pragma: no cover - diagnostics only
        return f"<Load {self.source} {self.records} records {'whole' if self.whole else 'adds-only'}>"


def plan_load(data: Path) -> tuple[list[Load], list[tuple[str, str]]]:
    """Choose one file per source, and say what was left out and why.

    Three things in a dump directory must not be treated as a catalogue:

    - An **empty** `<source>.ndjson`. A scrape that collected nothing says
      nothing about what the shop sells, but loading it and then retiring
      against it would mark that supplier's every product withdrawn. Seven
      suppliers in the v3 dump are in exactly this state.
    - A **partial** file for a source whose complete file has records. The
      complete file is the newer and fuller account; replaying the leftovers of
      an interrupted attempt over it would re-activate rows the complete dump
      had just retired.
    - A **partial** file as grounds for retirement. It is loaded when it is all
      there is, but only ever adds.
    """
    # The dump tool records, per source, whether this run actually wrote the file
    # and whether it stopped at a cap. Both bear on retirement, and neither is
    # visible from the filename. An older dump directory without a manifest keeps
    # the previous behaviour: a complete file is taken at face value.
    manifest: dict[str, dict] = {}
    manifest_path = data / "manifest.json"
    if manifest_path.exists():
        manifest = json.loads(manifest_path.read_text(encoding="utf-8")).get("sources", {})

    def authoritative(source: str) -> tuple[bool, str]:
        """Whether a complete file may be read as the whole of a catalogue."""
        if not manifest:
            return True, ""
        entry = manifest.get(source)
        if entry is None:
            return False, "no manifest entry for this run"
        return may_retire(entry.get("write_status"), entry.get("truncated"))

    plans: list[Load] = []
    skipped: list[tuple[str, str]] = []
    suffixes = (".partial.ndjson.gz", ".partial.ndjson", ".ndjson.gz", ".ndjson")
    names = sorted(
        {
            next(path.name[: -len(suffix)] for suffix in suffixes if path.name.endswith(suffix))
            for path in data.iterdir()
            if path.is_file() and any(path.name.endswith(suffix) for suffix in suffixes)
        }
    )
    for source in names:
        complete = next(
            (path for path in (data / f"{source}.ndjson.gz", data / f"{source}.ndjson") if path.exists()),
            data / f"{source}.ndjson.gz",
        )
        partial = next(
            (
                path
                for path in (data / f"{source}.partial.ndjson.gz", data / f"{source}.partial.ndjson")
                if path.exists()
            ),
            data / f"{source}.partial.ndjson.gz",
        )
        whole, half = records_in(complete), records_in(partial)
        if whole:
            trusted, why = authoritative(source)
            plans.append(Load(source, complete, trusted, whole))
            if not trusted:
                skipped.append((source, f"loaded as adds-only: {why}"))
            if half:
                skipped.append((source, f"{half} partial records, superseded by a complete dump"))
        elif half:
            plans.append(Load(source, partial, False, half))
        else:
            skipped.append((source, "no records in this dump"))
    return plans, skipped


